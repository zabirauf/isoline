// Copies the design-system tokens into the UI so the app never reaches outside app/ui at build time.
//   src/styles/tokens.css    the compiled CSS custom properties, verbatim
//   src/styles/bundle.css    the component classes (iso-*), verbatim
//   src/styles/tokens.gen.ts the color values per theme, for Monaco themes and the canvas map
// Run with: npm run tokens
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const ui = resolve(here, "..");
const ds = resolve(ui, "../../docs/handoff/design-system");

const css = readFileSync(resolve(ds, "tokens.css"), "utf8");
writeFileSync(resolve(ui, "src/styles/tokens.css"), css);
const bundle = readFileSync(resolve(ds, "project/components/bundle.css"), "utf8");
writeFileSync(resolve(ui, "src/styles/bundle.css"), bundle);

const json = JSON.parse(readFileSync(resolve(ds, "project/tokens.json"), "utf8"));
const light = {};
const dark = {};
for (const t of json.color.tokens) {
  light[t.name] = t.value.light;
  dark[t.name] = t.value.dark;
}
const ts = `// Generated by scripts/sync-tokens.mjs from docs/handoff/design-system/project/tokens.json. Do not edit.
export type ColorToken = ${Object.keys(light).map((k) => JSON.stringify(k)).join(" | ")};
export type ThemeColors = Record<ColorToken, string>;
export const LIGHT: ThemeColors = ${JSON.stringify(light, null, 2)};
export const DARK: ThemeColors = ${JSON.stringify(dark, null, 2)};
`;
writeFileSync(resolve(ui, "src/styles/tokens.gen.ts"), ts);
console.log(`tokens: ${Object.keys(light).length} colors`);
